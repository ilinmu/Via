    static func t(_ key: String, _ language: String) -> String {
        let table = language == "en" ? english : chinese
        return table[key] ?? key
    }

    static func duration(_ seconds: Int, _ language: String) -> String {
        let total = max(0, seconds)
        let hours = total / 3600
        let minutes = (total % 3600) / 60
        let rest = total % 60
        if hours > 0 {
            if minutes > 0 {
                return String(format: t("duration_hours_minutes", language), hours, minutes)
            }
            return String(format: t("duration_hours", language), hours)
        }
        if minutes > 0 {
            if rest > 0 {
                return String(format: t("duration_minutes_seconds", language), minutes, rest)
            }
            return String(format: t("duration_minutes", language), minutes)
        }
        return String(format: t("duration_seconds", language), rest)
    }

